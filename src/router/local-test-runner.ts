import * as fs from 'node:fs';
import * as path from 'node:path';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import type { QAFindConfig } from '../types/index.js';
import { loadConfig } from '../config/loader.js';
import { ensureDir } from '../utils/files.js';
import { logger } from '../utils/logger.js';

export interface LocalTestRunOptions {
  /** Spec file or directory. Defaults to `compiler.outputDir` from the config. */
  specPath?: string;
  /** Overrides Playwright's `use.baseURL`. Defaults to `baseUrl` from the config. */
  targetUrl?: string;
  /** Project directory that holds the QAFind config. Defaults to `process.cwd()`. */
  cwd?: string;
  config?: QAFindConfig;
  /** Extra arguments passed through to `playwright test`. */
  extraArgs?: string[];
}

export interface LocalTestRunResult {
  exitCode: number;
  passed: number;
  failed: number;
  flaky: number;
  skipped: number;
  testDir: string;
  configPath: string;
  reportPath: string;
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Resolve the Playwright Test CLI, preferring the copy installed in the user's project. */
export function resolvePlaywrightTestCli(cwd: string): string {
  const bases = [path.join(cwd, 'package.json'), import.meta.url];
  for (const base of bases) {
    try {
      return createRequire(base).resolve('@playwright/test/cli');
    } catch {
      // try the next base
    }
  }
  throw new Error(
    '@playwright/test is not installed. Install it next to qafind (for example `bun add -d @playwright/test`) to run specs locally.'
  );
}

function nodeBinary(): string {
  if (process.env.QAFIND_NODE_BIN) return process.env.QAFIND_NODE_BIN;
  // Playwright Test needs Node's worker and loader APIs, so never run it under Bun.
  return (process.versions as Record<string, string | undefined>).bun ? 'node' : process.execPath;
}

/** Derive a suite name from a spec path (e.g. `tests/checkout.spec.ts` -> `checkout`). */
export function suiteNameFromSpec(specPath: string | undefined, fallback: string): string {
  if (!specPath) return fallback;
  const base = path.basename(specPath).replace(/(\.(spec|test))?\.[cm]?[jt]sx?$/i, '');
  return base || fallback;
}

/**
 * Run spec file(s) with Playwright Test. Specs get the QAFind gateway and runner through the
 * `qafindTest` fixture exported from `src/testing/qafind-test.ts`.
 */
export async function runPlaywrightSpecs(options: LocalTestRunOptions = {}): Promise<LocalTestRunResult> {
  const cwd = options.cwd || process.cwd();
  const config = options.config || loadConfig(undefined, cwd);
  const specInput = options.specPath || config.compiler?.outputDir || './tests/generated';
  const target = path.resolve(cwd, specInput);

  if (!fs.existsSync(target)) {
    throw new Error(`Spec path not found: ${target}`);
  }

  const isFile = fs.statSync(target).isFile();
  const testDir = isFile ? path.dirname(target) : target;
  const workDir = path.join(cwd, '.qafind', 'playwright');
  ensureDir(workDir);
  const reportPath = path.join(workDir, 'results.json');
  const configPath = path.join(workDir, 'playwright.config.mjs');
  fs.rmSync(reportPath, { force: true });

  const baseConfig = {
    testDir,
    outputDir: path.join(workDir, 'test-results'),
    retries: 0,
    reporter: [['list'], ['json', { outputFile: reportPath }]],
    use: {
      browserName: 'chromium',
      baseURL: options.targetUrl || config.baseUrl,
      headless: config.browser?.headless ?? true,
      viewport: config.browser?.viewport,
      launchOptions: {
        executablePath: config.browser?.executablePath,
        slowMo: config.browser?.slowMo || undefined,
      },
    },
  };
  const testMatch = isFile ? `new RegExp(${JSON.stringify(`(^|[\\\\/])${escapeRegExp(path.basename(target))}$`)})` : 'undefined';
  fs.writeFileSync(
    configPath,
    `// Generated by qafind test --local. Do not edit.\n` +
    `const base = ${JSON.stringify(baseConfig, null, 2)};\n` +
    `const testMatch = ${testMatch};\n` +
    `export default testMatch ? { ...base, testMatch } : base;\n`,
    'utf8'
  );

  const cli = resolvePlaywrightTestCli(cwd);
  logger.info(`Running Playwright Test on ${path.relative(cwd, target) || '.'}`);

  const exitCode = await new Promise<number>((resolve, reject) => {
    const child = spawn(nodeBinary(), [cli, 'test', '--config', configPath, ...(options.extraArgs || [])], {
      cwd,
      stdio: 'inherit',
      env: { ...process.env, QAFIND_BASE_URL: options.targetUrl || config.baseUrl },
    });
    child.on('error', reject);
    child.on('exit', (code, signal) => resolve(code ?? (signal ? 1 : 0)));
  });

  let stats = { expected: 0, unexpected: 0, flaky: 0, skipped: 0 };
  if (fs.existsSync(reportPath)) {
    try {
      const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
      stats = { ...stats, ...(report.stats || {}) };
    } catch {
      logger.warn(`Could not parse Playwright JSON report at ${reportPath}`);
    }
  }

  return {
    exitCode,
    passed: stats.expected,
    failed: stats.unexpected,
    flaky: stats.flaky,
    skipped: stats.skipped,
    testDir,
    configPath,
    reportPath,
  };
}
